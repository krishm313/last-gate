import { createRequire } from "node:module";
import { execSync } from "node:child_process";
const require = createRequire(execSync("npm root -g").toString().trim() + "/");
const { chromium, devices } = require("playwright");
const browser = await chromium.launch();
const page = await (await browser.newContext({ ...devices["iPhone 13"], deviceScaleFactor: 3 })).newPage();
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.addInitScript(() => { localStorage.setItem("lastgate.seenTitle", "1"); localStorage.setItem("lastgate.tutorial", "done"); localStorage.setItem("lastgate.tipPreview", "1"); });
await page.goto("http://localhost:5180/"); await page.waitForTimeout(1500);
await page.evaluate(() => { __renderer.perfSample = () => {}; __renderer.maxDpr = 3; __renderer.fit(); });
await page.click(".chapter:not(.daily)", { force: true }); await page.waitForTimeout(1200);
await page.screenshot({ path: "rv_day.png" });
await page.evaluate(() => { const c = __camp(); for (const p of c.plots) if ((p.kind === "tower") && !p.locked) p.level = 2; c.hero.coins = 30; });
await page.getByRole("button", { name: /Start the night/ }).click({ force: true });
await page.waitForTimeout(9000);
await page.evaluate(() => { const c = __camp(); c.hero.x = 360; c.hero.y = 360; });
await page.waitForTimeout(2500);
await page.screenshot({ path: "rv_fight1.png" });
await page.waitForTimeout(1500);
await page.screenshot({ path: "rv_fight2.png" });
console.log({ errors }); await browser.close();
